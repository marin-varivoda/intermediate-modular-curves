// Independent exact Fricke matrix on a newly constructed X_0 canonical model.
load "canonical_input.m";
load "target_qseries.m";
M := CuspidalSubspace(ModularForms(N,2));
g := Dimension(M);
assert g eq expected_genus;
B := Matrix(Rationals(),[[Coefficient(qExpansion(f,precision),i):i in [1..precision-1]]:f in Basis(M)]);
assert Rank(B) eq g and Rank(target_basis) eq g;
L := Matrix(Rationals(),[Eltseq(Solution(B,v)):v in Rows(target_basis)]);
assert L*B eq target_basis;
W := L*AtkinLehnerOperator(M,N)*L^-1;
assert W^2 eq IdentityMatrix(Rationals(),g);
assert Rank(W+IdentityMatrix(Rationals(),g)) eq 1;
C := Curve(ProjectiveSpace(Rationals(),g-1),equations);
forms := [&+[W[i,j]*R.j:j in [1..g]]:i in [1..g]];
w := iso<C->C|forms,forms>;
G := AutomorphismGroup(C,[w]);
assert #G eq 2;
print "SUCCESS Fricke involution and genus-one invariant subspace";
Y,pi := CurveQuotient(G);
assert Genus(Y) eq 1;
P := pi(C!cusp_coordinates);
E,to_E := EllipticCurve(Y,P);
assert Conductor(E) eq N;
lo,hi := RankBounds(E);
assert lo eq 1 and hi eq 1;
print "ELLIPTIC coefficients",aInvariants(E);
print "QUOTIENT_MAP",DefiningPolynomials(pi);
print "SUCCESS degree-two positive-rank elliptic quotient";
quit;
