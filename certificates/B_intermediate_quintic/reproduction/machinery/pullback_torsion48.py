"""Torsion bounds using pullback to X1(48), with fresh full Manin maps.

Published input: Derickx et al., Sporadic Cubic Torsion, Theorem 4.13:
J1(48)(Q)_tors is generated by rational cusp-orbit divisors.
The lattice/transfer argument is in the paper, Section 7 (class R, level 48).
Classification acceptance requires the complete curve/divisor replay too.
"""
import argparse
import json
from math import gcd
from pathlib import Path
from sage.all import Cusp, GammaH, Matrix, ModularSymbols, QQ, ZZ, identity_matrix
from integer_lattices import dual, order


def rational_cuspidal_lattice(n):
    A = ModularSymbols(GammaH(n,[1,n-1]),2,sign=0)
    M = A.cuspidal_subspace()
    integral = M.integral_structure().basis_matrix().change_ring(QQ)
    assert A.manin_gens_to_basis().row_module(ZZ).intersection(
        A.boundary_map().matrix().left_kernel()) == integral.row_module(ZZ)
    split = integral.stack(A.eisenstein_subspace().basis_matrix())
    cusps = list(A.cusps())
    permutations = {}
    for a in range(1,n):
        if gcd(a,n)!=1:
            continue
        permutation = []
        for cusp in cusps:
            y = ZZ(cusp.denominator()) or ZZ(n)
            x = a*ZZ(cusp.numerator()) % n
            while gcd(x,y)!=1:
                x += n
            j,sign = A.boundary_space()._cusp_index(Cusp(x,y))
            assert j>=0 and sign in [-1,1]
            permutation.append(j)
        assert sorted(permutation)==list(range(len(cusps)))
        permutations[a] = permutation
    for a in permutations:
        for b in permutations:
            assert [permutations[a][j] for j in permutations[b]] == permutations[a*b % n]
    base = next(i for i in range(len(cusps)) if all(p[i]==i for p in permutations.values()))
    vectors = []
    for cusp in cusps:
        path = A([cusps[base],cusp]).element()
        assert path in A.integral_structure()
        vectors.append(list(split.solve_left(path)[:M.dimension()]))
    V = Matrix(QQ,vectors)
    change = M.basis_matrix().solve_left(integral)
    star = change*M.star_involution().matrix()*change.inverse()
    conjugate = Matrix(QQ,[V.row(j)-V.row(permutations[n-1][base]) for j in permutations[n-1]])
    assert all(c.denominator()==1 for c in (V*star-conjugate).list())
    generators = identity_matrix(QQ,M.dimension())
    unseen = set(range(len(cusps)))
    degrees = []
    while unseen:
        i = min(unseen)
        orbit = {p[i] for p in permutations.values()}
        unseen -= orbit
        degrees.append(len(orbit))
        generators = generators.stack(Matrix(QQ,[sum((V.row(j) for j in orbit),V.row(base))]))
    lattice = generators.row_module(ZZ)
    invariants = [int(a) for a in lattice.basis_matrix().inverse().change_ring(ZZ).elementary_divisors() if a!=1]
    # Independent published check: Sporadic Cubic Torsion, Table 2, N=48.
    assert invariants == [2,2,2,2,4,40,40,240,1436640]
    print('X1 genus',M.dimension()//2,'cusp orbit degrees',sorted(degrees),
          'rational cuspidal order',order(lattice),flush=True)
    return A,M,integral,lattice


def run(directory,bound):
    n = 48
    metadata = json.loads((directory/'relations.json').read_text())['invariants']
    assert metadata['level']==n
    A = ModularSymbols(GammaH(n,metadata['delta']),2,sign=0)
    M = A.cuspidal_subspace()
    assert M.dimension()==2*metadata['genus']
    integral = M.integral_structure().basis_matrix().change_ring(QQ)
    assert A.manin_gens_to_basis().row_module(ZZ).intersection(
        A.boundary_map().matrix().left_kernel()) == integral.row_module(ZZ)
    change = M.basis_matrix().solve_left(integral)
    I = identity_matrix(QQ,M.dimension())
    star = change*M.star_involution().matrix()*change.inverse()
    assert all(c.denominator()==1 for c in star.list())
    relations = (star-I).transpose().stack(bound*I)
    primes = [p for p in [7,11,13,17,19] if gcd(p,n*bound)==1]
    assert len(primes)>=2
    for p in primes:
        T = M.hecke_matrix(p)
        operator = change*(I-T+T*T-M.hecke_matrix(p*p))*change.inverse()
        assert all(c.denominator()==1 for c in operator.list())
        relations = relations.stack(operator.transpose())
    hecke = dual(relations.row_module(ZZ))
    A1,M1,integral1,rational1 = rational_cuspidal_lattice(n)
    delta = metadata['delta']
    representatives = sorted({min(a,n-a) for a in delta})
    degree = len(representatives)
    matrices = []
    for a in representatives:
        d = ZZ(a).inverse_mod(n)
        b = (a*d-1)//n
        assert a*d-b*n==1
        matrices.append((a,b,n,d))
    def transfer_symbol(symbol):
        a,b,c,d = symbol.lift_to_sl2z(n)
        value = A1(0)
        for r,s,t,u in matrices:
            value += A1([Cusp(r*b+s*d,t*b+u*d),Cusp(r*a+s*c,t*a+u*c)])
        return value.element()
    relative_transfer = Matrix(QQ,[list(transfer_symbol(s)) for s in A.manin_symbols_basis()])
    # Verify the formula on every generator, not merely the selected basis.
    presentation = A.manin_gens_to_basis()
    for i in range(presentation.nrows()):
        assert presentation.row(i)*relative_transfer == transfer_symbol(A.manin_symbols().manin_symbol(i))
    transferred = integral*relative_transfer
    transfer = integral1.solve_left(transferred)
    assert transfer*integral1==transferred
    assert all(c.denominator()==1 for c in transfer.list())
    relative_push = Matrix(QQ,[list(A(symbol.tuple()).element()) for symbol in A1.manin_symbols_basis()])
    pushed = integral1*relative_push
    push = integral.solve_left(pushed)
    assert push*integral==pushed
    assert all(c.denominator()==1 for c in push.list())
    assert transfer*push==degree*identity_matrix(QQ,M.dimension())
    change1 = M1.basis_matrix().solve_left(integral1)
    star = change*M.star_involution().matrix()*change.inverse()
    star1 = change1*M1.star_involution().matrix()*change1.inverse()
    assert transfer*star1==star*transfer
    for p in [7,11]:
        T = change*M.hecke_matrix(p)*change.inverse()
        T1 = change1*M1.hecke_matrix(p)*change1.inverse()
        assert transfer*T1==T*transfer
    print('verified integral transfer, pushforward, degree and real action',degree,flush=True)
    HB = hecke.basis_matrix()
    constraints = identity_matrix(QQ,M.dimension()).stack(
        (HB*transfer*rational1.basis_matrix().inverse()).transpose())
    restricted = (dual(constraints.row_module(ZZ)).basis_matrix()*HB).row_module(ZZ)
    assert I.row_module(ZZ).is_submodule(restricted)
    result = dict(status='PULLBACK_TORSION_UPPER_BOUND',level=n,delta=delta,
                  degree_to_intermediate=degree,old_hecke_bound=int(order(hecke)),
                  pullback_restricted_bound=int(order(restricted)),
                  x1_rational_cuspidal_order=int(order(rational1)))
    print(result,flush=True)
    (directory/'pullback_torsion48.json').write_text(json.dumps(result,indent=2)+'\n')
    print('SUCCESS exact full-homology pullback torsion bound',flush=True)


if __name__=='__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('directory',type=Path)
    parser.add_argument('--torsion-bound',type=int,required=True)
    args = parser.parse_args()
    run(args.directory,args.torsion_bound)
