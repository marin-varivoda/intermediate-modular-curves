"""Data for the double-cover argument: X = X1(N) -> Y = X_{+-1,+-a}(N) = X/<a>, a of order 2 mod +-1.

Writes <out> (a Magma file) containing:
  - Y's canonical model: coordinates y_0..y_{h-1} = Sage's integral basis of S_2(Gamma_H(N,[a])),
    relations of degree 2..maxdeg, each certified to the Sturm bound;
  - w = psi / y_0 with psi a cusp form on Gamma1(N) with <a> psi = -psi, and
    delta = w^2 = psi^2 / y_0^2 = Nm(y) / Dn(y), from the identity psi^2 Dn(y) = y_0^2 Nm(y) of
    weight-(2k+4) forms on Gamma_H(N,[a]), certified to the Sturm bound.
Usage (Sage's Python):  python dc_data.py N a maxdeg out.m
"""
import os, sys
import sage.all as S
from itertools import combinations_with_replacement as cwr

N, a, maxdeg, out = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3]), sys.argv[4]
GY = S.GammaH(N, [a])
idx = int(GY.projective_index())
SX = S.CuspForms(S.Gamma1(N), 2)
SY = S.CuspForms(GY, 2)
gX, h = SX.dimension(), SY.dimension()


def sturm(weight):
    return (weight * idx) // 12 + 1


PREC = sturm(2 * max(maxdeg, 5) + 4) + 5
R = S.PowerSeriesRing(S.QQ, "q", default_prec=PREC)
ys = [R(f.qexp(PREC).padded_list(PREC), PREC) for f in SY.integral_basis()]
assert len(ys) == h and ys[0].valuation() == 1

# psi: a cusp form on Gamma1(N) in the -1 eigenspace of the diamond operator <a>.
M = SX.diamond_bracket_matrix(a)
minus = (M + 1).kernel().basis()
assert len(minus) == gX - h
basis = [R(f.qexp(PREC).padded_list(PREC), PREC) for f in SX.basis()]
psi = sum(c * b for c, b in zip(minus[0], basis))
psi = psi * S.lcm([S.QQ(c).denominator() for c in psi.padded_list(PREC)])


def relations(forms, k, prec):
    """All homogeneous polynomial relations of degree k among forms, to precision prec."""
    mons = list(cwr(range(len(forms)), k))
    rows = []
    for m in mons:
        p = R(1)
        for i in m:
            p = p * forms[i]
        rows.append(p.padded_list(prec))
    K = S.matrix(S.QQ, rows).left_kernel().basis_matrix()
    return mons, K


# Y's canonical ideal, degrees 2..maxdeg. For maxdeg = 2 (Y of genus >= 5, not trigonal) take the
# quadrics from MD Sage: a basis over Z of the integral relations, in the same coordinates
# (Sage's integral basis), so that the model has the right reduction mod p.
ideal = []
if maxdeg == 2:
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../third_party/mdsage"))
    from mdsage import vanishing_quadratic_forms
    Q = vanishing_quadratic_forms(GY, minimize_strategy="LLL")
    for q in Q:
        terms = []
        for exps, coeff in q.dict().items():
            m = [i for i, e in enumerate(exps) for _ in range(e)]
            terms.append((m, int(coeff)))
        ideal.append(terms)
for k in range(2 if maxdeg > 2 else 3, maxdeg + 1):
    mons, K = relations(ys, k, sturm(2 * k))
    for row in K.rows():
        row = row * S.lcm([c.denominator() for c in row])
        ideal.append([(list(m), int(c)) for m, c in zip(mons, row) if c != 0])

# delta = Nm/Dn: psi^2 * Dn(y) - y0^2 * Nm(y) = 0, with Dn not in the ideal.
found = None
for k in range(1, 6):
    mons = list(cwr(range(h), k))
    prec = sturm(2 * k + 4)
    vals = []
    for m in mons:
        p = R(1)
        for i in m:
            p = p * ys[i]
        vals.append(p)
    rowsD = [(psi ** 2 * v).padded_list(prec) for v in vals]
    rowsN = [(-(ys[0] ** 2) * v).padded_list(prec) for v in vals]
    K = S.matrix(S.QQ, rowsD + rowsN).left_kernel().basis_matrix()
    # Discard solutions whose Dn vanishes on Y (then Nm does too): Dn(y) = 0 as a form.
    for row in K.rows():
        Dn = sum(c * v for c, v in zip(row[:len(mons)], vals))
        if Dn.truncate(prec) != 0:
            row = row * S.lcm([c.denominator() for c in row])
            found = (k, mons, row)
            break
    if found:
        break
assert found, "no delta found with k <= 5"
k, mons, row = found

with open(out, "w") as f:
    f.write(f"// Double-cover data for X1({N}) -> X_(+-1,+-{a})({N}); generated by dc_data.py\n")
    f.write(f"N := {N}; a := {a}; gX := {gX}; gY := {h}; indexY := {idx};\n")
    f.write("Rel := [" + ",\n  ".join("[" + ", ".join(f"<{m}, {c}>" for m, c in r) + "]" for r in ideal) + "];\n")
    f.write(f"delta_degree := {k};\n")
    f.write("Dn := [" + ", ".join(f"<{list(m)}, {int(c)}>" for m, c in zip(mons, row[:len(mons)]) if c != 0) + "];\n")
    f.write("Nm := [" + ", ".join(f"<{list(m)}, {int(c)}>" for m, c in zip(mons, row[len(mons):]) if c != 0) + "];\n")
print(f"N={N} a={a} gX={gX} gY={h} relations={len(ideal)} delta_degree={k} -> {out}")
