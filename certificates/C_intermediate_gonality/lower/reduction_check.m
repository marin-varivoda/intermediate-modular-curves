// Good reduction at p of each MD Sage model used for a CAGonality lower bound.
// The reduced quadrics must have the generic Hilbert polynomial (2g-2)t+1-g, so the reduction is the
// special fibre of the flat closure. It must be an irreducible curve of geometric genus g (hence
// smooth) with the rational point (1:0:...:0), the reduction of the cusp at infinity (hence
// geometrically integral). Run from this directory:  magma -b reduction_check.m
SetQuitOnError(true);
load "../models/41.168.11.b.1.m"; p := 2; assert N mod p ne 0;
Sp := Reduction(X, p); Ip := Ideal(Sp);
h := HilbertPolynomial(Ip); t := Parent(h).1; assert h eq (2*g-2)*t + 1-g;
Cp := Curve(Sp); assert IsIrreducible(Cp); assert Genus(Cp) eq g;
assert [1] cat [0 : i in [2..g]] in Cp;
printf "GOOD_REDUCTION %o p=%o\n", "41.168.11.b.1", p;
